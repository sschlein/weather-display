"""Renders the anti-aliased fonts and icons the display uses into src/fonts.cpp.

TFT_eSPI's built-in fonts are ASCII only, and the display needs umlauts, "°"
and weather icons. This writes TFT_eSPI smooth fonts (the .vlw format)
straight from Inter (SIL Open Font License) and the Tabler icon font (MIT),
both in tools/vendor, so no Processing sketch is needed. Each font only
carries the characters it is used for: flash is the display's tightest
budget.

    uv run --no-project --with pillow python tools/make_fonts.py
"""

import re
import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / "tools" / "vendor"
INTER = str(VENDOR / "{}.otf")

TEXT = sorted({chr(c) for c in range(0x20, 0x7F)} | set("äöüÄÖÜß°·…–↑↓"))
TEMPERATURE = sorted(set("0123456789,-°"))

# Tabler icon name → the name the firmware uses (ICON_<NAME>).
WEATHER = {
    "sun": "SUN",
    "moon": "MOON",
    "cloud": "CLOUD",
    "cloud-filled": "CLOUD_FILLED",
    "cloud-rain": "RAIN",
    "cloud-snow": "SNOW",
    "cloud-storm": "STORM",
    "cloud-fog": "FOG",
}
SMALL = {
    "droplet": "DROPLET",
    "wifi-off": "WIFI_OFF",
}


def codepoints(icons: dict) -> dict:
    css = (VENDOR / "tabler-icons.css").read_text()
    points = {}
    for tabler, name in icons.items():
        match = re.search(rf'\.ti-{re.escape(tabler)}:before\s*{{\s*content:\s*"\\([0-9a-f]+)"', css)
        if not match:
            raise SystemExit(f"Icon {tabler} not in tabler-icons.css")
        points[name] = chr(int(match[1], 16))
    return points


def vlw(path: str, size: int, chars) -> bytes:
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    metrics, bitmaps = b"", b""
    for char in chars:
        x0, y0, x1, y1 = font.getbbox(char, anchor="ls")
        width, height = max(0, x1 - x0), max(0, y1 - y0)
        if width and height:
            glyph = Image.new("L", (width, height), 0)
            ImageDraw.Draw(glyph).text((-x0, -y0), char, font=font, fill=255, anchor="ls")
            bitmaps += glyph.tobytes()
        advance = round(font.getlength(char))
        # unicode, height, width, xAdvance, dY (top above baseline), dX, padding
        metrics += struct.pack(">7i", ord(char), height, width, advance, -y0, x0, 0)
    header = struct.pack(">6i", len(chars), 11, size, 0, ascent, descent)
    return header + metrics + bitmaps


def main():
    weather, small = codepoints(WEATHER), codepoints(SMALL)
    tabler = str(VENDOR / "tabler-icons.ttf")
    weather_glyphs = sorted(weather.values())
    fonts = [
        # name, file, pixel size, characters
        ("FONT_SMALL", INTER.format("Inter-Medium"), 14, TEXT),
        ("FONT_TEXT", INTER.format("Inter-Regular"), 18, TEXT),
        ("FONT_VALUE", INTER.format("InterDisplay-SemiBold"), 24, TEXT),
        ("FONT_TEMPERATURE", INTER.format("InterDisplay-Medium"), 104, TEMPERATURE),
        ("ICONS_SMALL", tabler, 18, sorted(small.values())),
        ("ICONS_MEDIUM", tabler, 30, weather_glyphs),
        ("ICONS_LARGE", tabler, 96, weather_glyphs),
    ]

    # Declared in the header, defined once: a definition in the header put a
    # copy of every font into each file that included it.
    header = ["// Generated by tools/make_fonts.py. Do not edit.", "#pragma once", "#include <stdint.h>", ""]
    source = ["// Generated by tools/make_fonts.py. Do not edit.", '#include "fonts.h"', "#include <pgmspace.h>", ""]
    for name, path, size, chars in fonts:
        data = vlw(path, size, chars)
        header.append(f"extern const uint8_t {name}[];  // {Path(path).stem} {size}px, {len(data)} bytes")
        source.append(f"const uint8_t {name}[] PROGMEM = {{")
        for i in range(0, len(data), 24):
            source.append("  " + ",".join(f"0x{b:02x}" for b in data[i : i + 24]) + ",")
        source.append("};\n")
    header += ["", "// Icons, as UTF-8 strings for the ICONS_* fonts."]
    for name, char in {**weather, **small}.items():
        utf8 = "".join(f"\\x{b:02x}" for b in char.encode())
        header.append(f'#define ICON_{name} "{utf8}"')
    (ROOT / "include" / "fonts.h").write_text("\n".join(header) + "\n")
    (ROOT / "src" / "fonts.cpp").write_text("\n".join(source))
    print("\n".join(line for line in header if line.startswith("extern")))


if __name__ == "__main__":
    main()
